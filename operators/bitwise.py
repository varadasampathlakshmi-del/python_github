#Operators-Bitwiswe operators

p=12
q=10
print("p=",bin(p),"q=",bin(q))
print("p&q=",p&q)
print("p|q=",p|q)
print("p^q=",p^q)
print("~p=",~p)
print("p<<q=",p<<q)
print("p>>q=",p>>q)

#output
#p= 0b1100 q= 0b1010
#p&q= 8
#p|q= 14
#p^q= 6
#~p= -13
#p<<q= 12288
#p>>q= 0
