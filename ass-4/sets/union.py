set1 = {1, 2, 3, 4, 5}
set2 = {4, 5, 6, 7, 8}

print("Union:", set1 | set2)

print("Intersection:", set1 & set2)

print("Difference:", set1 - set2)

print("Symmetric Difference:", set1 ^ set2)
#output:-
#Union: {1, 2, 3, 4, 5, 6, 7, 8}
#Intersection: {4, 5}
#Difference: {1, 2, 3}
#Symmetric Difference: {1, 2, 3, 6, 7, 8}

