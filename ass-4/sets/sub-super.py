set1 = {1, 2, 3, 4, 5}
set2 = {2, 3, 4}

print("Is set2 a subset of set1?", set2.issubset(set1))

print("Is set1 a superset of set2?", set1.issuperset(set2))
#output:-
#Is set2 a subset of set1? True
#Is set1 a superset of set2? True
